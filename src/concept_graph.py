STYLE = {"is-a": "#2b6cb0", "part-of": "#2f855a"}
OTHER = "#9b2c2c"


# поняття словника, для яких у масиві знань ще немає жодного відношення
LONELY = ["Час_доби", "Ранковий_полив"]


def build_graph():
    G = nx.DiGraph()
    G.add_nodes_from(LONELY)
    for u, v, rel in EDGES:
        G.add_edge(u, v, label=rel)
    return G


def analyse(G):
    U = G.to_undirected()
    print(f"Вершин: {G.number_of_nodes()}, дуг: {G.number_of_edges()}")
    print("Ізольовані вершини:", list(nx.isolates(G)) or "немає")
    comps = list(nx.connected_components(U))
    print("Компонент зв'язності:", len(comps))
    top = sorted(U.degree, key=lambda x: -x[1])[:5]
    print("Найщільніші вузли:", ", ".join(f"{n} ({d})" for n, d in top))
    # вершини без жодного предметного відношення (лише is-a / part-of)
    only_struct = [n for n in G.nodes
                   if all(G.edges[e]["label"] in STYLE
                          for e in list(G.in_edges(n)) + list(G.out_edges(n)))]
    print("Лише структурні зв'язки:", ", ".join(only_struct))


def draw(G, path="docs/lab03_concept_graph.png"):
    pos = nx.spring_layout(G.to_undirected(), k=0.65, seed=68, iterations=300)
    # ізольовані вершини — у верхній лівий кут, щоб їх було видно
    xs = [p[0] for n, p in pos.items() if n not in LONELY]
    ys = [p[1] for n, p in pos.items() if n not in LONELY]
    for i, n in enumerate(LONELY):
        pos[n] = (min(xs), max(ys) - i * 0.08)
    colors = [STYLE.get(G.edges[e]["label"], OTHER) for e in G.edges]
    plt.figure(figsize=(24, 16))
    nx.draw_networkx_edges(G, pos, edge_color=colors, arrowsize=14,
                           width=1.2, node_size=2500)
    nx.draw_networkx_labels(G, pos, font_size=8,
                            bbox=dict(boxstyle="round,pad=0.3", fc="#E9EFF2",
                                      ec="#4a5568", lw=0.6))
    rel_labels = {e: G.edges[e]["label"] for e in G.edges
                  if G.edges[e]["label"] not in STYLE}
    nx.draw_networkx_edge_labels(G, pos, edge_labels=rel_labels,
                                 font_size=6, font_color=OTHER)
    legend = [Line2D([0], [0], color=STYLE["is-a"], lw=2, label="is-a"),
              Line2D([0], [0], color=STYLE["part-of"], lw=2, label="part-of"),
              Line2D([0], [0], color=OTHER, lw=2, label="предметні відношення")]
    plt.legend(handles=legend, loc="lower left", fontsize=10)
    plt.axis("off")
    plt.tight_layout()
    plt.savefig(path, dpi=150, bbox_inches="tight")
    print("Збережено:", path)


if __name__ == "__main__":
    G = build_graph()
    analyse(G)
    draw(G)
